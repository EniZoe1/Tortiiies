/**
 * Regenerates src/components/logo-data.ts and src/app/icon.svg from the
 * source artwork in /logo.svg. Run with: node scripts/build-logo.mjs
 *
 * The artwork itself is never edited — we only extract the path data and
 * crop the viewBox to the real content bounds (measured in a browser).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "logo.svg"), "utf8");

// Tight content bounds (+ small safety margin) inside the 1208x864 canvas.
const VIEWBOX = "116 149 1018 640";

// 1. strip comments (one of them contains a commented-out path)
const svg = source.replace(/<!--[\s\S]*?-->/g, "");

// 2. the mask that punches the hole in the "R" (so the page shows through)
const maskBlock = svg.match(/<mask[\s\S]*?<\/mask>/)[0];
const holePath = maskBlock.match(/<path[^>]*>/)[0];
const hole = {
  transform: holePath.match(/transform="([^"]+)"/)[1],
  d: holePath.match(/\sd="([^"]+)"/)[1],
};

// 3. every visible path, in paint order
const withoutDefs = svg.replace(/<defs>[\s\S]*?<\/defs>/, "");
const maskedBlock = withoutDefs.match(/<g mask=[\s\S]*?<\/g>/)[0];
const pathRe = /<path\s+([^>]*?)\/?>/g;

const parse = (attrs) => ({
  transform: attrs.match(/transform="([^"]+)"/)?.[1],
  d: attrs.match(/\sd="([^"]+)"/)?.[1] ?? attrs.match(/^d="([^"]+)"/)?.[1],
});

const paths = [];
let rest = withoutDefs;
const maskedPaths = [...maskedBlock.matchAll(pathRe)].map((m) => parse(m[1]));
rest = rest.replace(maskedBlock, "<!--MASKED-->");
for (const m of rest.matchAll(/<!--MASKED-->|<path\s+([^>]*?)\/?>/g)) {
  if (m[0] === "<!--MASKED-->") {
    maskedPaths.forEach((p) => paths.push({ ...p, masked: true }));
  } else {
    paths.push({ ...parse(m[1]), masked: false });
  }
}

const data = `// AUTO-GENERATED by scripts/build-logo.mjs from /logo.svg — do not edit by hand.
export const LOGO_VIEWBOX = ${JSON.stringify(VIEWBOX)};
export const LOGO_ASPECT = ${(() => {
  const [, , w, h] = VIEWBOX.split(" ").map(Number);
  return (w / h).toFixed(4);
})()};

export const LOGO_HOLE = ${JSON.stringify(hole)};

export const LOGO_PATHS: { transform?: string; d: string; masked: boolean }[] = ${JSON.stringify(
  paths,
  null,
  1,
)};
`;
writeFileSync(join(root, "src/components/logo-data.ts"), data);

// Static, theme-independent copy used as the favicon (Next: src/app/icon.svg)
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}">
<defs>
<mask id="h" maskUnits="userSpaceOnUse" x="0" y="0" width="1208" height="864"><rect width="1208" height="864" fill="#fff"/><path transform="${hole.transform}" d="${hole.d}" fill="#000"/></mask>
<linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%"><stop offset="0%" stop-color="#ffe47a"/><stop offset="50%" stop-color="#d4af37"/><stop offset="100%" stop-color="#d4af37"/></linearGradient>
</defs>
${paths
  .filter((p) => !p.masked)
  .map((p) => `<path transform="${p.transform}" d="${p.d}" fill="url(#g)"/>`)
  .join("\n")}
<g mask="url(#h)">${paths
  .filter((p) => p.masked)
  .map((p) => `<path transform="${p.transform}" d="${p.d}" fill="url(#g)"/>`)
  .join("")}</g>
</svg>
`;
writeFileSync(join(root, "src/app/icon.svg"), icon);

console.log(`logo-data.ts: ${paths.length} paths (${paths.filter((p) => p.masked).length} masked)`);
